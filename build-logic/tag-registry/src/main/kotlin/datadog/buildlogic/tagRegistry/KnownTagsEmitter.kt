package datadog.buildlogic.tagRegistry

import com.fasterxml.jackson.core.io.JsonStringEncoder
import java.util.Locale

/**
 * Emits the generated `KnownTags.java` from a [TagRegistry]. Public API first — per-tag
 * `<X>_NAME` (string) + `<X>_ID` (encoded long, literal) couplets with a trailing `// makeTagId(...)`
 * derivation comment — then the `<X>_SERIAL_NUM` constants, the
 * `StringIndex.EmbeddingSupport` keyOf table, the `NAMES_BY_SERIAL` array behind `nameOf`, and the
 * resolver's `openTelemetryNameOf` switch.
 */
object KnownTagsEmitter {

  fun emit(reg: TagRegistry, pkg: String, className: String): String {
    // Sanitize a tag name into a Java identifier base (not yet unique).
    fun sanitize(name: String): String {
      var c = name.uppercase().replace(Regex("[^A-Za-z0-9]"), "_").replace(Regex("_+"), "_").trim('_')
      if (c.isEmpty() || c[0].isDigit()) c = "T_$c"
      return c
    }

    // Collapse a duplicated trailing token so e.g. "resource.name" yields NAME (not NAME_NAME) and
    // "_dd.parent_id" yields ID (not ID_ID); the non-duplicating pairs (ID + _NAME -> ID_NAME, NAME
    // + _ID -> NAME_ID) are kept as-is.
    fun withSuffix(base: String, suffix: String) = if (base.endsWith(suffix)) base else "$base$suffix"

    // NAME/ID/SERIAL_NUM constants are all fields of the same generated class, so uniqueness must be
    // enforced on these FINAL suffixed identifiers, not on the pre-suffix base: two different base
    // names can collapse to the same final identifier once a suffix is appended -- e.g. base
    // "RESOURCE" suffixed with "_NAME" collides with a base that is already "RESOURCE_NAME" (which
    // withSuffix leaves untouched, since it already ends with "_NAME").
    val used = HashSet<String>()
    fun unique(name: String): String {
      var u = name
      var n = 2
      while (!used.add(u)) {
        u = "${name}_${n++}"
      }
      return u
    }

    val nameOfConst = HashMap<String, String>()
    val idOfConst = HashMap<String, String>()
    val serialOfConst = HashMap<String, String>()
    val otelNameOfConst = HashMap<String, String>()
    for (t in reg.tags) {
      val base = sanitize(t.name)
      nameOfConst[t.ddName] = unique(withSuffix(base, "_NAME"))
      idOfConst[t.ddName] = unique(withSuffix(base, "_ID"))
      serialOfConst[t.ddName] = unique(withSuffix(base, "_SERIAL_NUM"))
      // Suffix the pre-suffix base (not nameC), same as the other three: suffixing an
      // already-suffixed identifier would produce a redundant compound like NAME_OTEL_NAME.
      if (t.otelName != null) otelNameOfConst[t.ddName] = unique(withSuffix(base, "_OTEL_NAME"))
    }
    fun nameC(ddName: String) = nameOfConst.getValue(ddName)
    fun idC(ddName: String) = idOfConst.getValue(ddName)
    fun serialC(ddName: String) = serialOfConst.getValue(ddName)
    fun otelNameC(ddName: String) = otelNameOfConst.getValue(ddName)

    val keyOfOrder = reg.tags.map { it.ddName } // stable emit order
    // OpenTelemetry names that denote a different tag depending on the span's direction. keyOf
    // ignores direction (a shared Datadog name such as server.port resolves to its own tag);
    // directionalKeyOf(name, direction) switches on each one's tag per direction.
    val directional = sortedMapOf<String, MutableMap<TagConventions.Direction, String>>()
    for (t in reg.tags) {
      for ((direction, otel) in t.scopedOtelNames) {
        directional.getOrPut(otel) { mutableMapOf() }[direction] = t.ddName
      }
    }
    return buildString {
      // Public API first (name + encoded id couplets), so readers see the useful parts up top; the
      // serial ids and keyOf/resolver machinery follow below. Derivation is in the trailing comment.
      appendLine(
        """
        package $pkg;

        import datadog.trace.util.StringIndex;

        // GENERATED by the tag-registry code generator (dd-trace-java.tag-registry-generator).
        // DO NOT EDIT. Source: tag-conventions.yaml.
        public final class $className {

          // ---- tags ----
        """.trimIndent()
      )

      for (t in reg.tags) {
        appendLine("  public static final String ${nameC(t.ddName)} = \"${escape(t.ddName)}\";")
        appendLine("  public static final long ${idC(t.ddName)} = ${hex(t.id)};")
        if (t.otelName != null) {
          appendLine("  public static final String ${otelNameC(t.ddName)} = \"${escape(t.otelName)}\";")
        }
        append("// makeTagId(serial=${t.serial})")
        append(if (t.slot == TagRegistry.NO_SLOT) " + no slot" else " + slot=${t.slot}")
        if (t.traceLevel) append(" + trace-level")
        if (t.intercepted) append(" + intercepted")
        if (t.sharesSlot) append(" + shares slot")
        if (t.otelName != null) append(" -> ${escape(t.otelName)}")
        for ((direction, otel) in t.scopedOtelNames) append(" -> ${escape(otel)} (${direction.yamlKey})")
        appendLine("  <${escape(t.required)}>")
        appendLine()
      }

      // Serial numbers (globalSerial per tag) — public, so a switch on KnownTagCodec.serialNum outside
      // this package (the resolver here, TagInterceptor in core) can name them as case labels.
      // Per-direction aliases: each OpenTelemetry name that names a tag on spans of one direction, as
      // that tag's id. Code that knows its direction writes in OpenTelemetry terms by id
      // (Outbound.SERVER_ADDRESS_ID is PEER_HOSTNAME_ID) without knowing the Datadog name, and
      // without a lookup. Direction-free renames are repeated in each, so one class covers a span.
      for (direction in TagConventions.Direction.entries) {
        val aliases = sortedMapOf<String, String>()
        for (t in reg.tags) {
          val otel = t.otelName ?: t.scopedOtelNames[direction] ?: continue
          aliases[otel] = t.ddName
        }
        if (aliases.isEmpty()) continue
        val holder = DIRECTION_CLASS.getValue(direction)
        appendLine("  /** OpenTelemetry names on ${DIRECTION_SPANS.getValue(direction)} spans, as the ids of the tags they name. */")
        appendLine("  public static final class $holder {")
        val local = HashSet<String>()
        for ((otel, ddName) in aliases) {
          var constant = withSuffix(sanitize(otel), "_ID")
          var n = 2
          while (!local.add(constant)) constant = "${withSuffix(sanitize(otel), "_ID")}_${n++}"
          appendLine("    /** {@code ${escape(otel)}}: {@code ${escape(ddName)}}. */")
          appendLine("    public static final long $constant = $className.${idC(ddName)};")
        }
        appendLine()
        appendLine("    private $holder() {}")
        appendLine("  }")
        appendLine()
      }

      appendLine("  // ---- serial numbers ----")
      for (t in reg.tags) {
        appendLine("  public static final int ${serialC(t.ddName)} = ${t.serial};")
      }
      // Every known tag's serial is below SERIAL_LIMIT; serial 0 is no tag.
      val serialLimit = (reg.tags.maxOfOrNull { it.serial } ?: 0) + 1
      appendLine("  public static final int SERIAL_LIMIT = $serialLimit;")
      // Slots in use: every slotted tag's slot is below SLOT_COUNT.
      val slotCount = (reg.tags.filter { it.slot != TagRegistry.NO_SLOT }.maxOfOrNull { it.slot } ?: -1) + 1
      appendLine("  public static final int SLOT_COUNT = $slotCount;")

      // OpenTelemetry name -> canonical tag name. Validation ensures aliases are distinct from all
      // canonical names. Sort by OTel name to keep output deterministic.
      val otelByCanonical =
        reg.tags
          .mapNotNull { t -> t.otelName?.let { it to t.ddName } }
          .sortedBy { it.first }

      // keyOf table (open-addressed, via StringIndex.EmbeddingSupport). Canonical names first, then
      // OpenTelemetry names -- an OTel name resolves to its canonical tag's id (there is no distinct id
      // for it), so keyOf(otelName) == keyOf(canonical); nameOf still returns the canonical name.
      appendLine(
        """
        
          private static final String[] KEYOF_NAMES = {
        """.trimIndent()
      )
      keyOfOrder.forEach { appendLine("    ${nameC(it)},") }
      otelByCanonical.forEach { (otel, _) ->
        appendLine("    \"${escape(otel)}\",")
      }
      appendLine(
        """
          };
          private static final long[] KEYOF_VALUES = {
        """.trimIndent()
      )
      keyOfOrder.forEach { appendLine("    ${idC(it)},") }
      otelByCanonical.forEach { (_, canonical) ->
        appendLine("    ${idC(canonical)},")
      }
      // Resolver. KnownTagCodec.Installed links to this field directly, so merely resolving a tag
      // name initializes this class -- there is no registration step and no ordering to get wrong.
      appendLine(
        """
            };
          private static final int[] KEYOF_HASHES;
          private static final String[] KEYOF_KEYS;
          private static final long[] KEYOF_IDS;

          static {
            StringIndex.Data data = StringIndex.EmbeddingSupport.create(KEYOF_NAMES);
            long[] ids = new long[data.names.length];
            for (int j = 0; j < KEYOF_NAMES.length; j++) {
              ids[StringIndex.EmbeddingSupport.indexOf(data.hashes, data.names, KEYOF_NAMES[j])] =
                  KEYOF_VALUES[j];
            }
            KEYOF_HASHES = data.hashes;
            KEYOF_KEYS = data.names;
            KEYOF_IDS = ids;
          }

          /**
           * Each tag's Datadog name, indexed by serial; slot 0 (no tag) is null. An array rather than a
           * switch keeps nameOf small enough to inline at every caller.
           */
          static final String[] NAMES_BY_SERIAL = {
            null,
        """.trimIndent()
      )
      for (t in reg.tags.sortedBy { it.serial }) {
        appendLine("    ${nameC(t.ddName)},")
      }
      appendLine(
        """
          };

          /**
           * The registry's name&harr;id tables, as a {@link KnownTagCodec.Resolver}. {@code KnownTagCodec}
           * reads this field from its own holder, so the two classes complete each other: the codec owns
           * the bit layout and the naming policy, this class owns the data. Nothing has to be called first.
           */
          static final KnownTagCodec.Resolver RESOLVER =
              new KnownTagCodec.Resolver() {
                @Override
                public String nameOf(long tagId) {
                  int serial = KnownTagCodec.serialNum(tagId);
                  return serial < NAMES_BY_SERIAL.length ? NAMES_BY_SERIAL[serial] : null;
                }
        
                // openTelemetryNameOf: id -> OTel-namespace name on spans of a direction, null when
                // the tag has none there. The caller (a serializer) owns any fall-back-to-Datadog-name
                // policy.
                @Override
                public String openTelemetryNameOf(long tagId, int direction) {
                  switch (KnownTagCodec.serialNum(tagId)) {
        """.trimIndent()
      )
      for (t in reg.tags) {
        val result =
          if (t.otelName != null) {
            otelNameC(t.ddName)
          } else if (t.scopedOtelNames.isNotEmpty()) {
            // Renamed only on spans of some directions: elsewhere, and while the direction is
            // unknown, the tag keeps its Datadog name.
            t.scopedOtelNames.entries.reversed().fold("null") { rest, (direction, otel) ->
              "direction == KnownTagCodec.DIRECTION_${direction.name} ? \"${escape(otel)}\" : $rest"
            }
          } else {
            continue
          }
        appendLine("case ${serialC(t.ddName)}:")
        appendLine("  return $result;")
      }
      appendLine(
        """
                  default:
                    return null;
                }
              }

              @Override
              public long keyOf(String name) {
                int slot = StringIndex.EmbeddingSupport.indexOf(KEYOF_HASHES, KEYOF_KEYS, name);
                return slot < 0 ? 0L : KEYOF_IDS[slot];
              }

              @Override
              public long directionalKeyOf(String name, int direction) {
                switch (name) {
        """.trimIndent()
      )
      for ((name, byDirection) in directional) {
        appendLine("    case \"${escape(name)}\":")
        appendLine("      switch (direction) {")
        for (d in TagConventions.Direction.entries) {
          val tag = byDirection[d] ?: continue
          appendLine("        case KnownTagCodec.DIRECTION_${d.name}:")
          appendLine("          return ${idC(tag)};")
        }
        appendLine("        default:")
        appendLine("          return 0L;")
        appendLine("      }")
      }
      appendLine(
        """
                  default:
                    return 0L;
                }
              }
            };

        private $className() {}
      }
        """.trimIndent()
      )
    }
  }

  private val DIRECTION_CLASS =
    mapOf(
      TagConventions.Direction.INBOUND to "Inbound",
      TagConventions.Direction.OUTBOUND to "Outbound",
      TagConventions.Direction.NONE to "Internal",
    )

  private val DIRECTION_SPANS =
    mapOf(
      TagConventions.Direction.INBOUND to "server and consumer",
      TagConventions.Direction.OUTBOUND to "client and producer",
      TagConventions.Direction.NONE to "internal",
    )

  private fun hex(id: Long): String = "0x%016XL".format(Locale.ROOT, id)

  private fun escape(value: String): String = String(JsonStringEncoder.getInstance().quoteAsString(value))
}
