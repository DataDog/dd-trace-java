package datadog.trace.lambda;

import static datadog.trace.api.sampling.PrioritySampling.SAMPLER_DROP;
import static datadog.trace.api.sampling.PrioritySampling.SAMPLER_KEEP;
import static datadog.trace.api.sampling.PrioritySampling.UNSET;
import static datadog.trace.lambda.LambdaEventData.get;
import static datadog.trace.lambda.LambdaEventData.object;
import static datadog.trace.lambda.LambdaEventData.scalar;
import static datadog.trace.lambda.LambdaEventData.string;

import datadog.trace.api.DD128bTraceId;
import datadog.trace.api.DDTraceId;
import datadog.trace.api.TracePropagationStyle;
import datadog.trace.bootstrap.instrumentation.api.AgentSpanContext;
import datadog.trace.core.propagation.ExtractedContext;
import datadog.trace.core.propagation.PropagationTags;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.Locale;
import java.util.Map;

/** Contexts generated by AWS events; an unset sampling priority must remain unset. */
final class LambdaGeneratedContext {
  private LambdaGeneratedContext() {}

  static AgentSpanContext xray(String header) {
    if (!header.startsWith("Root=")) {
      return null;
    }
    String root = "";
    String parent = "";
    String sampled = "";
    for (String field : header.split(";")) {
      if (field.startsWith("Root=")) {
        root = field.substring(5);
      } else if (field.startsWith("Parent=")) {
        parent = field.substring(7);
      } else if (field.startsWith("Sampled=") && sampled.isEmpty()) {
        sampled = field.substring(8);
      }
    }
    if (!root.matches("1-[0-9a-fA-F]{8}-[0-9a-fA-F]{24}") || !parent.matches("[0-9a-fA-F]{16}")) {
      return null;
    }
    try {
      long traceId = Long.parseUnsignedLong(root.substring(19), 16);
      long parentId = Long.parseUnsignedLong(parent, 16);
      if (traceId == 0 || parentId == 0) {
        return null;
      }
      boolean datadog = root.substring(11, 19).equals("00000000");
      int priority =
          "1".equals(sampled)
              ? SAMPLER_KEEP
              : datadog && "0".equals(sampled) ? SAMPLER_DROP : UNSET;
      return new ExtractedContext(
          DDTraceId.from(traceId),
          parentId,
          priority,
          null,
          PropagationTags.factory().empty(),
          TracePropagationStyle.XRAY);
    } catch (NumberFormatException ignored) {
      return null;
    }
  }

  static LambdaTrigger stepFunctions(Map<String, Object> event) {
    for (String key : new String[] {"Payload", "_datadog"}) {
      if (event.containsKey(key)) {
        event = object(event.get(key));
      }
    }
    String execution = string(event, "Execution", "Id");
    String name = string(event, "State", "Name");
    String entered = string(event, "State", "EnteredTime");
    if (execution.isEmpty() || name.isEmpty() || entered.isEmpty()) {
      return null;
    }
    try {
      String root = string(event, "RootExecutionId");
      byte[] traceHash = hash(root.isEmpty() ? execution : root);
      long low = positive(traceHash, 8);
      long high = positive(traceHash, 0);
      String tags = "_dd.p.tid=" + String.format(Locale.ROOT, "%016x", high);
      if (event.containsKey("x-datadog-trace-id") && event.containsKey("x-datadog-tags")) {
        try {
          low = Long.parseUnsignedLong(string(event, "x-datadog-trace-id"));
        } catch (NumberFormatException ignored) {
          low = positive(hash(execution), 8);
        }
        tags = string(event, "x-datadog-tags");
        high =
            PropagationTags.factory()
                .fromHeaderValue(PropagationTags.HeaderType.DATADOG, tags)
                .getTraceIdHighOrderBits();
      }
      String parent = execution + "#" + name + "#" + entered;
      String retry = counter(get(event, "State", "RetryCount"));
      String redrive = counter(get(event, "Execution", "RedriveCount"));
      if (!"0".equals(retry) || !"0".equals(redrive)) {
        parent += "#" + retry + "#" + redrive;
      }
      LambdaTrigger trigger =
          new LambdaTrigger("states", string(event, "StateMachine", "Id"), true);
      trigger.generatedContext =
          new ExtractedContext(
              DD128bTraceId.from(high, low),
              positive(hash(parent), 0),
              SAMPLER_KEEP,
              "states",
              PropagationTags.factory().fromHeaderValue(PropagationTags.HeaderType.DATADOG, tags),
              TracePropagationStyle.DATADOG);
      return trigger;
    } catch (NoSuchAlgorithmException ignored) {
      return null;
    }
  }

  private static String counter(Object value) {
    try {
      int count = Integer.parseInt(scalar(value));
      return count >= 0 && count <= 65535 ? Integer.toString(count) : "0";
    } catch (NumberFormatException ignored) {
      return "0";
    }
  }

  private static byte[] hash(String value) throws NoSuchAlgorithmException {
    return MessageDigest.getInstance("SHA-256").digest(value.getBytes(StandardCharsets.UTF_8));
  }

  private static long positive(byte[] hash, int offset) {
    long value = ByteBuffer.wrap(hash, offset, 8).getLong() & Long.MAX_VALUE;
    return value == 0 ? 1 : value;
  }
}
