  // These values fail if the configured rate is narrowed to a float.
  @TableTest({SAMPLE_RATE_COLUMN, SAMPLE_RATE_0_123456789, SAMPLE_RATE_0_999999999})
  void preservesConfiguredSampleRate(double rate) {
    assertEquals(rate, new DeterministicSampler.TraceSampler(rate).getSampleRate());
  }

  @ParameterizedTest(name = "rate={0}")
  @MethodSource("testCutoffCalculationArguments")
  void testCutoffCalculation(int rate) {
    // Groovy's integer division uses BigDecimal arithmetic, equivalent to double precision
    // here
    long cutoff = DeterministicSampler.cutoff(rate / 100.0);

    BigDecimal cutoffFactor =
        new BigDecimal(BigInteger.valueOf(2).pow(64).subtract(BigInteger.ONE));
    long expected =
        new BigDecimal(rate / 100D).multiply(cutoffFactor).toBigInteger().longValue()
            + Long.MIN_VALUE;
    assertTrue(Math.abs(cutoff - expected) <= 1);
  }

  static Stream<Arguments> testCutoffCalculationArguments() {
    return IntStream.rangeClosed(0, 100).mapToObj(Arguments::arguments);
  }
