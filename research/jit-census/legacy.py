#!/usr/bin/env python3
"""Legacy vs current: oldest and newest cached version of each library.

  python3 -I legacy.py select <gradle files-2.1 root> <dest>   # hard-links jars into <dest>/{oldest,newest}/g/a/v/x/
  python3 -I legacy.py compare <oldest out-dir> <newest out-dir> > legacy.md

Only libraries whose oldest and newest cached versions differ in their first numeric component
are selected, so each pair spans at least one major version.
"""
import csv
import os
import re
import shutil
import sys
from collections import defaultdict

FAST = "SPLIT_FASTPATH"
IMPLICIT = {"String.split", "String.matches", "String.replaceAll", "String.replaceFirst", "Pattern.matches"}


def vkey(v):
    out = []
    for p in re.split(r"[.\-]", v):
        out.append((0, int(p), "") if p.isdigit() else (1, 0, p))
    return out


def major(v):
    m = re.match(r"\d+", v)
    return int(m.group()) if m else None


def binary_jars(d):
    found = []
    for dirpath, _, files in os.walk(d):
        for f in files:
            if f.endswith(".jar") and not f.endswith(("-sources.jar", "-javadoc.jar", "-test-sources.jar")):
                found.append(os.path.join(dirpath, f))
    return found


def select(root, dest):
    picked = 0
    for g in sorted(os.listdir(root)):
        if g.startswith("com.datadoghq") or not os.path.isdir(os.path.join(root, g)):
            continue
        for a in sorted(os.listdir(os.path.join(root, g))):
            adir = os.path.join(root, g, a)
            if not os.path.isdir(adir):
                continue
            vers = [v for v in os.listdir(adir) if binary_jars(os.path.join(adir, v))]
            if len(vers) < 2:
                continue
            vers.sort(key=vkey)
            old, new = vers[0], vers[-1]
            if major(old) is None or major(new) is None or major(old) == major(new):
                continue
            for label, v in (("oldest", old), ("newest", new)):
                d = os.path.join(dest, label, g, a, v, "x")
                os.makedirs(d, exist_ok=True)
                for j in binary_jars(os.path.join(adir, v)):
                    t = os.path.join(d, os.path.basename(j))
                    if not os.path.exists(t):
                        try:
                            os.link(j, t)
                        except OSError:
                            shutil.copy2(j, t)
            picked += 1
    print(f"selected {picked} libraries")


def load(d):
    lib = {}
    for row in csv.DictReader(open(os.path.join(d, "sites.csv"), newline="")):
        g, a, v = row["artifact"].split(":", 2)
        e = lib.setdefault(f"{g}:{a}", {"version": v, "classes": int(row["classes"]), "kinds": defaultdict(int)})
        if row["site_kind"] and row["shape"] != FAST and "used-directly" not in row["shape"]:
            e["kinds"][row["site_kind"]] += int(row["count"])
    return lib


def per_k(n, c):
    return 1000.0 * n / c if c else 0.0


def compare(old_dir, new_dir):
    old, new = load(old_dir), load(new_dir)
    both = sorted(set(old) & set(new))
    kinds = sorted({k for d in (old, new) for e in d.values() for k in e["kinds"]})
    oc = sum(old[x]["classes"] for x in both)
    nc = sum(new[x]["classes"] for x in both)
    print("# Legacy vs current (generated by legacy.py; do not edit)\n")
    print(f"{len(both)} libraries, oldest vs newest cached version (pairs span at least one major version).")
    print(f"Classes: oldest {oc:,}, newest {nc:,}.\n")
    print("## Sites per 1,000 classes, by method\n")
    print("| method | oldest | newest | ratio |")
    print("|---|---:|---:|---:|")
    for k in kinds + ["implicit per-call compiles", "all addressable"]:
        if k == "implicit per-call compiles":
            o = sum(v for x in both for kk, v in old[x]["kinds"].items() if kk in IMPLICIT)
            n = sum(v for x in both for kk, v in new[x]["kinds"].items() if kk in IMPLICIT)
        elif k == "all addressable":
            o = sum(sum(old[x]["kinds"].values()) for x in both)
            n = sum(sum(new[x]["kinds"].values()) for x in both)
        else:
            o = sum(old[x]["kinds"].get(k, 0) for x in both)
            n = sum(new[x]["kinds"].get(k, 0) for x in both)
        po, pn = per_k(o, oc), per_k(n, nc)
        ratio = f"{po / pn:.2f}x" if pn else "n/a"
        print(f"| {k} | {po:.1f} | {pn:.1f} | {ratio} |")

    def imp(e):
        return sum(v for kk, v in e["kinds"].items() if kk in IMPLICIT)

    rows = []
    for x in both:
        o, n = old[x], new[x]
        if o["classes"] < 50 or n["classes"] < 50:
            continue
        rows.append((x, o, n, per_k(imp(o), o["classes"]), per_k(imp(n), n["classes"])))
    better = sum(1 for r in rows if r[3] > r[4])
    worse = sum(1 for r in rows if r[3] < r[4])
    print(f"\nPer library (≥50 classes in both versions, {len(rows)} libraries): implicit per-call compiles per 1k classes "
          f"went **down** from oldest to newest in {better}, up in {worse}, unchanged in {len(rows) - better - worse}.\n")
    print("## Biggest drops from oldest to newest (implicit per-call compiles per 1k classes)\n")
    print("| library | oldest | newest | oldest /1k | newest /1k |")
    print("|---|---|---|---:|---:|")
    for x, o, n, po, pn in sorted(rows, key=lambda r: -(r[3] - r[4]))[:25]:
        print(f"| {x} | {o['version']} | {n['version']} | {po:.1f} | {pn:.1f} |")
    print("\n## Biggest increases\n")
    print("| library | oldest | newest | oldest /1k | newest /1k |")
    print("|---|---|---|---:|---:|")
    for x, o, n, po, pn in sorted(rows, key=lambda r: (r[3] - r[4]))[:10]:
        print(f"| {x} | {o['version']} | {n['version']} | {po:.1f} | {pn:.1f} |")


if __name__ == "__main__":
    if sys.argv[1] == "select":
        select(sys.argv[2], sys.argv[3])
    else:
        compare(sys.argv[2], sys.argv[3])
