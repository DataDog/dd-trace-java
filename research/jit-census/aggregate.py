#!/usr/bin/env python3
"""Roll up per-run sites.csv files into totals.md.

usage: python3 -I aggregate.py <out-dir> [<out-dir> ...] > totals.md
Each out-dir holds a sites.csv written by Census.java (artifact,classes,site_kind,shape,count).
"""
import csv
import os
import sys
from collections import defaultdict

FAST = "SPLIT_FASTPATH"

def main(dirs):
    shape_sites = defaultdict(int)
    shape_libs = defaultdict(set)
    lib_sites = defaultdict(int)
    lib_classes = {}
    lib_run = {}
    run_libs = defaultdict(set)
    for d in dirs:
        run = os.path.basename(os.path.normpath(d))
        with open(os.path.join(d, "sites.csv"), newline="") as f:
            for row in csv.DictReader(f):
                a = row["artifact"]
                lib_classes[a] = int(row["classes"])
                lib_run[a] = run
                run_libs[run].add(a)
                if not row["site_kind"]:
                    continue
                n = int(row["count"])
                key = (row["site_kind"], row["shape"])
                shape_sites[key] += n
                shape_libs[key].add(a)
                if row["shape"] != FAST and "used-directly" not in row["shape"]:
                    lib_sites[a] += n

    print("# Census totals (generated by aggregate.py; do not edit)\n")
    print("Runs: " + ", ".join(f"{r} ({len(run_libs[r])} libs)" for r in sorted(run_libs)))
    print(f"\nLibraries: {len(lib_classes)}, classes: {sum(lib_classes.values()):,}\n")

    print("## Sites by method and shape\n")
    print("| method | shape | sites | libraries |")
    print("|---|---|---:|---:|")
    for (k, s), n in sorted(shape_sites.items(), key=lambda x: (x[0][0], -x[1])):
        print(f"| {k} | {s} | {n:,} | {len(shape_libs[(k, s)])} |")

    print("\n## Libraries by addressable sites (excluding split fast path)\n")
    print("| library | run | classes | sites | sites / 1k classes |")
    print("|---|---|---:|---:|---:|")
    for a, n in sorted(lib_sites.items(), key=lambda x: -x[1])[:60]:
        c = lib_classes[a]
        print(f"| {a} | {lib_run[a]} | {c:,} | {n:,} | {1000.0 * n / max(c, 1):.1f} |")

if __name__ == "__main__":
    main(sys.argv[1:])
