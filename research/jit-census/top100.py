#!/usr/bin/env python3
"""Render top100.md: coverage status of the curated target list.

usage: python3 -I top100.py > top100.md      (run from research/jit-census)
"""
import csv
import os
import re

here = os.path.dirname(os.path.abspath(__file__))


def covered():
    status = {}
    base = os.path.join(here, "out", "sites.csv")
    if os.path.exists(base):
        for row in csv.DictReader(open(base, newline="")):
            g, a, v = row["artifact"].split(":", 2)
            status.setdefault(f"{g}:{a}", f"baseline ({v})")
    batch = None
    for line in open(os.path.join(here, "batches.txt")):
        line = line.strip()
        if line.startswith("# "):
            batch = line[2:]
        elif line:
            g, a, v = line.split(":", 2)
            status[f"{g}:{a}"] = f"{batch} ({v})"
    return status


IMPLICIT = {"String.split", "String.matches", "String.replaceAll", "String.replaceFirst", "Pattern.matches"}


def load_run(d):
    out = {}
    path = os.path.join(here, d, "sites.csv")
    if not os.path.exists(path):
        return out
    for row in csv.DictReader(open(path, newline="")):
        g, a, v = row["artifact"].split(":", 2)
        e = out.setdefault(f"{g}:{a}", {"v": v, "classes": int(row["classes"]), "implicit": 0, "all": 0, "replace": 0})
        if not row["site_kind"] or row["shape"] == "SPLIT_FASTPATH" or "used-directly" in row["shape"]:
            continue
        n = int(row["count"])
        e["all"] += n
        if row["site_kind"] in IMPLICIT:
            e["implicit"] += n
        if row["site_kind"] == "String.replace(CS,CS)":
            e["replace"] += n
    return out


def per_k(e, k):
    return f"{1000.0 * e[k] / e['classes']:.1f}" if e and e["classes"] else ""


def main():
    status = covered()
    current = load_run("out")
    for d in sorted(os.listdir(here)):
        if d.startswith("out-batch"):
            current.update(load_run(d))
    oldest = load_run("out-legacy-oldest")
    rows = []
    for line in open(os.path.join(here, "top100.txt")):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        rows.append((parts[0], parts[1], "legacy" in parts[2:]))
    done = sum(1 for r in rows if r[0] in status)
    print("# Target list coverage (generated by top100.py; do not edit)\n")
    print(f"{done} of {len(rows)} covered. Curated list, not ranked by downloads; `legacy` marks the legacy track.\n")
    print("Per 1k classes: **implicit** = per-call compiles via split/matches/replaceAll/replaceFirst/Pattern.matches;")
    print("**+JDK8** adds `replace(CS,CS)`, which also compiles a Pattern on JDK 8. *Oldest* = oldest cached version, where it differs by a major version.\n")
    print("| library | category | legacy | covered by | classes | implicit /1k | +JDK8 /1k | all /1k | oldest | oldest implicit /1k | oldest +JDK8 /1k |")
    print("|---|---|---|---|---:|---:|---:|---:|---|---:|---:|")
    for ga, cat, legacy in rows:
        c, o = current.get(ga), oldest.get(ga)
        jdk8 = lambda e: f"{1000.0 * (e['implicit'] + e['replace']) / e['classes']:.1f}" if e and e["classes"] else ""
        print(f"| {ga} | {cat} | {'yes' if legacy else ''} | {status.get(ga, '**pending**')} | "
              f"{c['classes'] if c else ''} | {per_k(c, 'implicit')} | {jdk8(c)} | {per_k(c, 'all')} | "
              f"{o['v'] if o else ''} | {per_k(o, 'implicit')} | {jdk8(o)} |")
    pending = [ga for ga, _, _ in rows if ga not in status]
    print(f"\n## Pending ({len(pending)})\n")
    print(" ".join(pending))


if __name__ == "__main__":
    main()
